"""Write ontology/TAXONOMY.md: the collateral taxonomy as a tree, with the limits stored on each class.

Run:  uv run python scripts/export_taxonomy.py   (re-run after changing ontology/taxonomy_collateral.ttl)
"""

from rdflib import RDFS
from rdflib.namespace import SKOS

from mortgage_assistant.rules.case import RABO
from mortgage_assistant.rules.engine import ONTOLOGY_DIR, ontology_graph

LIMITS = [  # (property on the class, how to show it)
    (RABO.interestOnlyAllowed, lambda v: "interest-only " + ("allowed" if str(v) == "true" else "**not allowed**")),
    (RABO.lettingAllowed, lambda v: "letting allowed" if str(v) == "true" else ""),
    (RABO.requiresConditions, lambda v: "**Plus conditions only**"),
    (RABO.requiresNHG, lambda v: "**only with NHG**"),
    (RABO.requiresOwnHomeAtRabobank, lambda v: "applicant must own a home financed by Rabobank"),
    (RABO.maxTermYears, lambda v: f"max term {v} years"),
    (RABO.mooringMaxTermYears, lambda v: f"mooring repaid in {v} years"),
    (RABO.maxAreaHectares, lambda v: f"max {v} ha"),
    (RABO.noBusinessUse, lambda v: "no business use"),
    (RABO.requiresValuationReport, lambda v: "valuation report required (no construction costs)"),
]


def short(term) -> str:
    return str(term).split("#")[-1]


def main() -> None:
    g = ontology_graph()

    def label(cls, lang):
        for lit in g.objects(cls, SKOS.prefLabel):
            if lit.language == lang:
                return str(lit)
        return short(cls)

    norms: dict = {}
    for norm in g.subjects(RABO.forCollateral, None):
        cls = g.value(norm, RABO.forCollateral)
        ltv = float(g.value(norm, RABO.maxLTV))
        val = g.value(norm, RABO.forValuation)
        text = f"{ltv:.0%}" + (f" with {label(val, 'en')}" if val is not None else "")
        for extra, name in ((RABO.mooringMaxLTV, "mooring"), (RABO.businessPartMaxLTV, "business part")):
            if (x := g.value(norm, extra)) is not None:
                text += f" + {float(x):.0%} of the {name}"
        norms.setdefault(cls, []).append(text)

    def describe(cls) -> str:
        bits = []
        if cls in norms:
            bits.append("max LTV " + "; ".join(sorted(norms[cls])))
        allowed = sorted(label(v, "en") for v in g.objects(cls, RABO.allowedValuation))
        if allowed:
            bits.append("valuation: " + " / ".join(allowed))
        for prop, fmt in LIMITS:
            for v in g.objects(cls, prop):
                if (t := fmt(v)):
                    bits.append(t)
        return "; ".join(bits)

    def tree(cls, depth: int, lines: list[str]) -> None:
        sections = ", ".join(sorted(str(s) for s in g.objects(cls, RABO.definedIn)))
        info = describe(cls)
        lines.append(f"{'    ' * depth}- **{label(cls, 'en')}** · *{label(cls, 'nl')}* · `rabo:{short(cls)}`"
                     + (f" · {sections}" if sections else "") + (f"  \n{'    ' * depth}  {info}" if info else ""))
        for child in sorted(g.subjects(RDFS.subClassOf, cls), key=short):
            tree(child, depth + 1, lines)

    lines = ["# Collateral taxonomy (generated by scripts/export_taxonomy.py; do not edit by hand)", "",
             "Source: `ontology/taxonomy_collateral.ttl` (DRAFT, to be reviewed against Acceptatiebeleid chapter 5). "
             "A property belongs to one class per **dimension**: e.g. a *regular house* (building type) that is "
             "*partly let* (use), a *project build* (construction) on *erfpacht* (legal right). Limits on a parent class "
             "apply to all its sub-classes; when several LTV norms apply, the **lowest** wins.", ""]
    for dim in ("building type", "use", "construction", "legal right"):
        lines += [f"## Dimension: {dim}", ""]
        for top in sorted(g.subjects(RABO.dimension, None), key=short):
            if str(g.value(top, RABO.dimension)) == dim:
                tree(top, 0, lines)
        lines.append("")
    lines += ["## Valuation types", ""]
    tree(RABO.Valuation, 0, lines)
    out = ONTOLOGY_DIR / "TAXONOMY.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"-> {out}")


if __name__ == "__main__":
    main()
