"""Step 1: PDF -> sections -> chunks, saved to data/processed/.

Run:  uv run python scripts/parse_pdf.py

Outputs
  sections.jsonl        one line per section (with number, title, pages, text)
  chunks.jsonl          one line per chunk (what we embed and search)
  definitions.jsonl     the terms of Bijlage 2 (Definitielijst), one per line
  sections_preview.md   the same sections as readable Markdown, for a human check
"""

import statistics

from mortgage_assistant.config import settings
from mortgage_assistant.ingest import chunk_sections, parse_pdf
from mortgage_assistant.ingest.definitions import parse_definitions
from mortgage_assistant.ingest.io import write_jsonl


def main() -> None:
    out = settings.processed_dir
    out.mkdir(parents=True, exist_ok=True)

    sections = parse_pdf(settings.pdf_path)
    chunks = chunk_sections(sections, settings.chunk_max_chars, settings.chunk_overlap_chars)

    definitions = parse_definitions(settings.pdf_path)

    write_jsonl(out / "sections.jsonl", [s.to_dict() for s in sections])
    write_jsonl(out / "definitions.jsonl", [d.to_dict() for d in definitions])
    write_jsonl(out / "chunks.jsonl", [c.to_dict() | {"heading_path": c.heading_path} for c in chunks])

    with open(out / "sections_preview.md", "w", encoding="utf-8") as f:
        f.write("# Parsed sections (generated by scripts/parse_pdf.py, do not edit)\n\n")
        for s in sections:
            f.write(f"{'#' * min(s.level + 1, 6)} [{s.id}] {s.number} {s.title}  \n")
            f.write(f"*part: {s.part} | pages: {s.pages}*\n\n{s.text}\n\n")

    lengths = [len(c.text) for c in chunks]
    print(f"sections: {len(sections)} ({sum(1 for s in sections if s.text)} with text)")
    print(f"definitions: {len(definitions)} | sections with 🔍 icon: {sum(s.explain_icon for s in sections)}")
    print(f"chunks:   {len(chunks)}  chars min/median/max: "
          f"{min(lengths)}/{int(statistics.median(lengths))}/{max(lengths)}")
    for part in ("Versiebeheer", "Acceptatiebeleid", "Beheerbeleid", "Bijlagen"):
        print(f"  {part:17} {sum(1 for c in chunks if c.part == part)} chunks")
    print(f"written to {out}")


if __name__ == "__main__":
    main()
