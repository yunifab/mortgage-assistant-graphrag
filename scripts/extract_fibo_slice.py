"""Extract the small slice of FIBO that our mortgage ontology reuses -> ontology/fibo_slice.ttl

Why a slice? FIBO is huge (hundreds of files, deep imports). We only need ~20 terms. So we copy
just those terms (their label, definition, direct parent and the FIBO file they come from) and
refer to them by their official FIBO address (IRI). This is a common practice called MIREOT
("minimum information to reference an external ontology term").

Run:  uv run python scripts/extract_fibo_slice.py
Needs: the FIBO git clone in ./fibo (git clone https://github.com/edmcouncil/fibo.git)
"""

from pathlib import Path

from rdflib import Graph, Literal, Namespace, URIRef
from rdflib.namespace import OWL, RDF, RDFS, SKOS

ROOT = Path(__file__).resolve().parents[1]
FIBO_DIR = ROOT / "fibo"
OUT = ROOT / "ontology" / "fibo_slice.ttl"
BASE = "https://spec.edmcouncil.org/fibo/ontology/"

# (FIBO file, term) for every FIBO term we use
TERMS = [
    ("LOAN/LoansGeneral/LoanApplications.rdf", "LoanApplication"),
    ("LOAN/LoansGeneral/LoanApplications.rdf", "UnderwritingDecision"),
    ("LOAN/LoansGeneral/LoanApplications.rdf", "CreditRiskAssessment"),
    ("LOAN/LoansGeneral/LoanApplications.rdf", "hasRequestedAmount"),
    ("LOAN/LoansGeneral/Loans.rdf", "Loan"),
    ("LOAN/LoansGeneral/Loans.rdf", "LoanToValueRatio"),
    ("LOAN/LoansGeneral/Loans.rdf", "isInterestOnly"),
    ("LOAN/RealEstateLoans/Mortgages.rdf", "Mortgage"),
    ("LOAN/RealEstateLoans/MortgageOrigination.rdf", "MortgageIndemnityGuarantee"),
    ("FBC/DebtAndEquities/Debt.rdf", "Borrower"),
    ("FBC/DebtAndEquities/Debt.rdf", "Collateral"),
    ("FBC/DebtAndEquities/Debt.rdf", "PrincipalRepaymentTerms"),
    ("FND/Arrangements/Assessments.rdf", "Appraisal"),
    ("FND/Arrangements/Assessments.rdf", "Appraiser"),
    ("FND/Arrangements/Assessments.rdf", "MarketValue"),
    ("FND/Places/RealProperty.rdf", "RealProperty"),
    ("BE/LegalEntities/LegalPersons.rdf", "LegallyCompetentNaturalPerson"),
]
CMNS_DEFINITION = URIRef("https://www.omg.org/spec/Commons/AnnotationVocabulary/definition")


def main() -> None:
    out = Graph()
    out.bind("owl", OWL), out.bind("rdfs", RDFS), out.bind("skos", SKOS)
    out.add((URIRef(BASE + "slice"), RDF.type, OWL.Ontology))
    out.add((URIRef(BASE + "slice"), RDFS.comment, Literal(
        "Slice of FIBO terms reused by the Rabobank mortgage ontology. Generated by "
        "scripts/extract_fibo_slice.py from the local FIBO clone; do not edit by hand.")))

    for rel_path, term in TERMS:
        module = BASE + rel_path.removesuffix(".rdf") + "/"
        out.bind("fibo-" + rel_path.split("/")[-1].removesuffix(".rdf").lower(), Namespace(module))
        iri = URIRef(module + term)
        g = Graph().parse(FIBO_DIR / rel_path, format="xml")
        if (iri, None, None) not in g:
            raise SystemExit(f"{term} not found in {rel_path}")
        for kind in (OWL.Class, OWL.ObjectProperty, OWL.DatatypeProperty):
            if (iri, RDF.type, kind) in g:
                out.add((iri, RDF.type, kind))
        for label in g.objects(iri, RDFS.label):
            out.add((iri, RDFS.label, label))
        for definition in list(g.objects(iri, SKOS.definition)) + list(g.objects(iri, CMNS_DEFINITION)):
            out.add((iri, SKOS.definition, definition))
        for parent in g.objects(iri, RDFS.subClassOf):
            if isinstance(parent, URIRef):  # skip anonymous restrictions; keep named parents only
                out.add((iri, RDFS.subClassOf, parent))
        out.add((iri, RDFS.isDefinedBy, URIRef(module)))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    out.serialize(OUT, format="turtle")
    print(f"{len(TERMS)} FIBO terms -> {OUT} ({len(out)} triples)")


if __name__ == "__main__":
    main()
